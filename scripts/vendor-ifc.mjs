/**
 * VENDOR THE CONTRACTS' IFC CODEC — contracts/src/ifc (the one GlobalId rule,
 * ifcGuid, and the small MIT STEP reader/writer, parseStep/writeStep) bundled
 * with esbuild into vendor/apk-contracts/apk-ifc.js, one dependency-free ES
 * module this app loads with no build step (and the static public site too);
 * and contracts/src/ifc/dxf.ts (IFC on a DXF's hidden APK_IFC layer,
 * apk-ifc-dxf/1, ROAD-3598) into vendor/apk-contracts/apk-ifc-dxf.js.
 *
 *   node scripts/vendor-ifc.mjs           write the bundles
 *   node scripts/vendor-ifc.mjs --check   exit 1 when a bundle is not what contracts/src/ifc builds to today
 *
 * Needs the monorepo checkout (../../../../../contracts with its node_modules);
 * on its own this repo keeps the committed bundle and the check says it skipped.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { createRequire } from 'node:module';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const APP = resolve(HERE, '..');
export const CONTRACTS = resolve(APP, '../../../../../contracts');
export const BUNDLE = join(APP, 'vendor/apk-contracts/apk-ifc.js');
export const DXF_BUNDLE = join(APP, 'vendor/apk-contracts/apk-ifc-dxf.js');

const header = (source, what) =>
  '/* Part of the APK.audio project — http://APK.audio — made by Anthony Kuzub\n' +
  '   MIT Licence. Free, for everyone, for ever. Full text in LICENSE at the root.\n' +
  `   GENERATED by scripts/vendor-ifc.mjs — DO NOT EDIT. Source: contracts/${source}\n` +
  `   (${what}). Regenerate: node scripts/vendor-ifc.mjs */\n`;
const HEADER = header('src/ifc/index.ts', 'ifcGuid + the STEP reader/writer');

/** The bundle as contracts/src/ifc builds to today, or null when contracts (or its esbuild) is not here. */
export async function buildBundle(source = 'src/ifc/index.ts', head = HEADER) {
  const entry = join(CONTRACTS, source);
  const esbuildPath = join(CONTRACTS, 'node_modules/esbuild');
  if (!existsSync(entry) || !existsSync(esbuildPath)) return null;
  const { build } = createRequire(join(CONTRACTS, 'package.json'))('esbuild');
  const out = await build({
    absWorkingDir: CONTRACTS,
    entryPoints: [source],
    bundle: true,
    format: 'esm',
    platform: 'neutral',
    target: 'es2020',
    charset: 'utf8',
    legalComments: 'none',
    minifyWhitespace: true,
    minifySyntax: true,
    metafile: true,
    write: false,
  });
  const foreign = Object.keys(out.metafile.inputs).filter((p) => p.includes('node_modules'));
  if (foreign.length) throw new Error(`contracts/src/ifc must stay dependency-free; it pulled in ${foreign.join(', ')}`);
  return head + out.outputFiles[0].text;
}

/** The DXF helper's bundle (addIfcToDxf, readIfcDxf, ifcDxfBlobs), or null as above. */
export const buildDxfBundle = () => buildBundle('src/ifc/dxf.ts', header('src/ifc/dxf.ts', 'IFC on the hidden APK_IFC layer of a DXF, apk-ifc-dxf/1'));

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const bundles = [[BUNDLE, await buildBundle()], [DXF_BUNDLE, await buildDxfBundle()]];
  if (bundles.some(([, text]) => text == null)) {
    console.log('vendor-ifc: contracts/ is not beside this app — kept the committed bundles');
  } else if (process.argv.includes('--check')) {
    let stale = false;
    for (const [path, text] of bundles) {
      const now = existsSync(path) ? readFileSync(path, 'utf8') : '';
      if (now !== text) {
        console.error(`vendor-ifc: ${path.slice(APP.length + 1)} is stale — run node scripts/vendor-ifc.mjs`);
        stale = true;
      }
    }
    if (stale) process.exit(1);
    console.log('vendor-ifc: fresh');
  } else {
    for (const [path, text] of bundles) {
      writeFileSync(path, text);
      console.log(`vendor-ifc: wrote ${path} (${text.length} bytes)`);
    }
  }
}
